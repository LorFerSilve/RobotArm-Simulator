#include "robotics/kinematics/PathPlanning2D.hpp"
#include "robotics/kinematics/ForwardKinematics.hpp"

#include <cmath>
#include <iostream>
#include <numbers>
#include <stdexcept>
#include <vector>

using robotics::kinematics::Joint2D;
using robotics::kinematics::JointLimits2D;
using robotics::kinematics::MotionSettings2D;
using robotics::kinematics::PlannedMotion2D;
using robotics::kinematics::forwardKinematics;
using robotics::kinematics::hasSelfCollision;
using robotics::kinematics::planJointPath2D;
using robotics::math::Vec2;

constexpr double dt = 1.0 / 60.0;
constexpr double pi = std::numbers::pi;

void verifyPath(const std::vector<Joint2D>& arm, const std::vector<JointLimits2D>& limits,
                const std::vector<std::vector<double>>& points) {
    for (std::size_t k = 1; k < points.size(); ++k) {
        for (int sub = 0; sub <= 60; ++sub) {
            const double t = sub / 60.0;
            auto temp = arm;
            for (std::size_t i = 0; i < temp.size(); ++i) {
                temp[i].angle = points[k - 1][i] * (1.0 - t) + points[k][i] * t;
                if (temp[i].angle < limits[i].minAngle - 1e-8 ||
                    temp[i].angle > limits[i].maxAngle + 1e-8)
                    throw std::runtime_error("Planned path violates joint limit");
            }
            if (hasSelfCollision(forwardKinematics(temp), 0.1))
                throw std::runtime_error("Planned path self-intersects");
        }
    }
}

void follow(std::vector<Joint2D>& arm, const std::vector<JointLimits2D>& limits,
            Vec2 target, int frames=1400) {
    PlannedMotion2D motion;
    motion.setTarget(arm, limits, target);
    if (!motion.pathAvailable()) throw std::runtime_error("No path found");
    bool reached=false;
    for (int frame = 0; frame < frames; ++frame) {
        const auto before = arm;
        const auto status = motion.advance(arm, limits, dt);
        if (status.blocked) throw std::runtime_error("Follower blocked");
        for (std::size_t i = 0; i < arm.size(); ++i) {
            const auto& bound = limits[i];
            if (arm[i].angle < bound.minAngle - 1e-8 ||
                arm[i].angle > bound.maxAngle + 1e-8)
                throw std::runtime_error("Joint left its limits");
            if (std::abs(arm[i].angularVelocity) > std::min(2.0, bound.maxAngularSpeed) + 1e-8)
                throw std::runtime_error("Speed limit exceeded");
            if (std::abs(arm[i].angularVelocity - before[i].angularVelocity) >
                std::min(6.0, bound.maxAngularAcceleration) * dt + 1e-8)
                throw std::runtime_error("Acceleration limit exceeded");
        }
        if (hasSelfCollision(forwardKinematics(arm), 0.1))
            throw std::runtime_error("Follower collision");
        if (status.reached) { reached=true; break; }
    }
    if (!reached) throw std::runtime_error("Follower did not converge");
}

int main() {
    try {
        std::vector<Joint2D> three{{1.25, 0.3, 0}, {0.75, -0.7, 0}, {1.1, 0.8, 0}};
        std::vector<JointLimits2D> bounds{{-2*pi, 2*pi, 2, 6},
                                          {-pi + .16, -.16, 2, 6},
                                          {.16, pi - .16, 2, 6}};
        auto path = planJointPath2D(three, bounds, {1.6, 1.1});
        if (!path.found() || path.terminalError > 0.005)
            throw std::runtime_error("Expected 3-joint path");
        verifyPath(three, bounds, path.waypoints);
        follow(three, bounds, {1.6, 1.1});
        follow(three, bounds, {-1.0, -.4}); // reconfigure from a different pose

        std::vector<Joint2D> four{{1.25, .3, 0}, {.75, -.7, 0}, {1.1, .8, 0},
                                   {.7, -.85, 0}};
        auto bound4=bounds;
        bound4.push_back({-pi+.16, -.16, 1.1, 2.5});
        follow(four, bound4, {1.3, 1.2});

        std::vector<Joint2D> six{{1.25, -2.82223, 0}, {.75, -.929347, 0},
                                  {1.1, .96359, 0}, {.7, -2.6477, 0},
                                  {.7, .517674, 0}, {.7, -2.94787, 0}};
        auto bound6=bounds;
        bound6.push_back({-pi+.16, -.16, 2, 6});
        bound6.push_back({.16, pi-.16, 2, 6});
        bound6.push_back({-pi+.16, -.16, 2, 6});
        Vec2 goal{-0.5, 1.0};
        // The desired tip is generated by another safe configuration, not an
        // arbitrary point that might be outside the constrained workspace.
        auto end=six;
        end[0].angle=-.516422;end[1].angle=-.762525;end[2].angle=.81884;
        end[3].angle=-2.93789;end[4].angle=.463875;end[5].angle=-2.00892;
        goal=forwardKinematics(end).back();
        // Regression: directly blending these two valid poses crosses another
        // arm segment; picking the endpoint alone is not a safe motion plan.
        bool directUnsafe = false;
        for (int step = 1; step <= 100; ++step) {
            auto intermediate = six;
            const double fraction = static_cast<double>(step) / 100.0;
            for (std::size_t i = 0; i < six.size(); ++i) {
                intermediate[i].angle = six[i].angle +
                    fraction * (end[i].angle - six[i].angle);
            }
            if (hasSelfCollision(forwardKinematics(intermediate), 0.1)) {
                directUnsafe = true;
                break;
            }
        }
        if (!directUnsafe)
            throw std::runtime_error("Regression setup no longer crosses links");
        auto path6=planJointPath2D(six, bound6, goal);
        if(!path6.found())throw std::runtime_error("Expected redundant 6-joint solution");
        verifyPath(six,bound6,path6.waypoints);
        follow(six,bound6,goal,2500);

        const auto unreachable = planJointPath2D(three, bounds, {10, 10});
        if (unreachable.found()) throw std::runtime_error("Out-of-reach goal accepted");
        PlannedMotion2D missing;
        missing.setTarget(three, bounds, {10, 10});
        if (!missing.searchFailed()) throw std::runtime_error("Missing path not reported");
        const auto prev = forwardKinematics(three).back();
        auto status = missing.advance(three, bounds, dt);
        if (!status.blocked || (forwardKinematics(three).back() - prev).length() > 1e-12)
            throw std::runtime_error("Blocked robot should stay put");
        std::cout << "Path planning and follow tests passed\n";
    } catch(const std::exception& ex) {
        std::cerr << "FAILED: " << ex.what() << '\n';
        return 1;
    }
}
